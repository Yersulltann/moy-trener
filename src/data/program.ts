export type WorkoutId = 'A' | 'B' | 'C' | 'pool';

export interface Exercise {
  id: string;
  name: string;
  equipment: string;
  sets: number;
  repsMin: number;
  repsMax: number;
  /** для планки и удержаний — работа на время, сек */
  timed?: boolean;
  perSide?: boolean;
  /** упражнение со * — только если голеностоп не болит */
  ankle?: boolean;
  /** для прогрессии: ноги +2,5 кг, верх +1–2 кг */
  legs?: boolean;
  /** без веса (планка, мёртвый жук) */
  bodyweight?: boolean;
  rest: number;
  tips: string[];
  mistake: string;
}

export interface Workout {
  id: WorkoutId;
  title: string;
  day: string;
  exercises: Exercise[];
}

